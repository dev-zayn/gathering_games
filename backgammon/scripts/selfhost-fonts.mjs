/**
 * Regenerates the self-hosted web fonts: `src/fonts/*.woff2` + `src/fonts.css`.
 *
 * The app never asks fonts.googleapis.com / gstatic.com for anything at runtime
 * — a game frame may be offline on a shared Wi-Fi, and
 * boot is the scarcest thing it has. So the css2 output is mirrored once, here:
 * the same files Google serves, from our own origin, with `font-display: swap`.
 *
 * Only the subsets the app actually paints are kept (Arabic copy, Latin digits
 * pip counts and room codes). Re-run after changing FAMILIES or SUBSETS:
 *
 *   bun run fonts
 *
 * Dependency-free on purpose (Node ≥ 18 `fetch`).
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** The café's hand (Ruqʿa: titles, the dice call) ships statics; the interface face is variable. */
const FAMILIES = 'family=Aref+Ruqaa:wght@400;700&family=Readex+Pro:wght@300..700'
const SUBSETS = new Set(['arabic', 'latin'])

// css2 picks the format from the UA — a current Chromium gets woff2 + unicode-range.
const UA =
  'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Mobile Safari/537.36'

const css = await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`, {
  headers: { 'User-Agent': UA },
}).then((res) => {
  if (!res.ok) throw new Error(`css2 answered ${res.status}`)
  return res.text()
})

const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g)]
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

mkdirSync(resolve(root, 'src/fonts'), { recursive: true })

const out = [
  '/* Self-hosted Google Fonts (Aref Ruqaa + Readex Pro) — byte-identical',
  '   mirror of the css2 output, with src URLs pointing at ./fonts/ (bundled beside the CSS).',
  '   Generated by scripts/selfhost-fonts.mjs; do not edit by hand. */',
]
const downloaded = new Map()

for (const [, subset, block] of blocks) {
  if (!SUBSETS.has(subset)) continue
  const family = /font-family: '([^']+)'/.exec(block)?.[1]
  const weight = /font-weight: ([\d ]+);/.exec(block)?.[1]?.trim().replace(' ', '-')
  const url = /src: url\(([^)]+)\)/.exec(block)?.[1]
  if (!family || !weight || !url) throw new Error(`unparsed @font-face for ${subset}`)

  const file = `${slug(family)}-${subset}-${weight}.woff2`
  if (!downloaded.has(url)) {
    const bytes = Buffer.from(await fetch(url).then((res) => res.arrayBuffer()))
    writeFileSync(resolve(root, 'src/fonts', file), bytes)
    downloaded.set(url, file)
    console.log(`  ${file} (${bytes.length} B)`)
  }
  out.push(`/* ${subset} */`, block.replace(url, `./fonts/${downloaded.get(url)}`))
}

writeFileSync(resolve(root, 'src/fonts.css'), `${out.join('\n')}\n`)
console.log(`fonts ok (${downloaded.size} files) → src/fonts.css`)
